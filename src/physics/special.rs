use std::f64::consts::PI;

fn poly(t: f64, c: &[f64]) -> f64 {
    c.iter().rev().fold(0.0, |a, &k| a * t + k)
}

fn asymptotic(x: f64, f: &[f64], th: &[f64], base: f64) -> f64 {
    let t = 3.0 / x;
    poly(t, f) * (x - base + poly(t, th)).cos() / x.sqrt()
}

pub fn j0(x: f64) -> f64 {
    let x = x.abs();
    if x <= 3.0 {
        return poly((x / 3.0).powi(2), &[1.0, -2.2499997, 1.2656208, -0.3163866, 0.0444479, -0.0039444, 0.00021]);
    }
    asymptotic(
        x,
        &[0.79788456, -0.00000077, -0.0055274, -0.00009512, 0.00137237, -0.00072805, 0.00014476],
        &[0.0, -0.04166397, -0.00003954, 0.00262573, -0.00054125, -0.00029333, 0.00013558],
        PI / 4.0,
    )
}

pub fn j1(x: f64) -> f64 {
    let a = x.abs();
    let v = if a <= 3.0 {
        a * poly((a / 3.0).powi(2), &[0.5, -0.56249985, 0.21093573, -0.03954289, 0.00443319, -0.00031761, 0.00001109])
    } else {
        asymptotic(
            a,
            &[0.79788456, 0.00000156, 0.01659667, 0.00017105, -0.00249511, 0.00113653, -0.00020033],
            &[0.0, 0.12499612, 0.0000565, -0.00637879, 0.00074348, 0.00079824, -0.00029166],
            3.0 * PI / 4.0,
        )
    };
    v.copysign(x)
}

pub fn airy(v: f64) -> f64 {
    if v.abs() < 1e-9 { 1.0 } else { (2.0 * j1(v) / v).powi(2) }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bessel_zeros() {
        assert!(j0(2.404826).abs() < 1e-5);
        assert!(j1(3.831706).abs() < 1e-5);
        assert!((j0(10.0) + 0.245936).abs() < 1e-5);
        assert!((j1(10.0) - 0.043473).abs() < 1e-5);
    }
}
